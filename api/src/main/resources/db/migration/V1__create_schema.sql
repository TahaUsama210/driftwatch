-- Driftwatch schema, version 1.
--
-- Conventions:
--   * Enumerations (status, severity, category, direction) are text with CHECK constraints rather
--     than Postgres enum types: the value sets are owned by the API contract, and changing a CHECK
--     constraint is a plain migration whereas enum types cannot drop values.
--   * Length limits mirror the API contract's validation limits as a second line of defence.
--   * Timestamps are timestamptz and always written in UTC.
--   * Server-generated ids use uuidv7() (built into Postgres 18): time-ordered, so new rows land at
--     the right-hand edge of the primary key index. Scan ids are generated by the agent instead.

CREATE TABLE hosts (
    id             uuid         NOT NULL DEFAULT uuidv7(),
    machine_id     varchar(64)  NOT NULL,
    -- Lower-case hex SHA-256 of the agent token. The token itself is never stored.
    token_hash     char(64)     NOT NULL,
    hostname       varchar(255) NOT NULL,
    os_id          varchar(64)  NOT NULL,
    os_version     varchar(64),
    os_pretty_name varchar(255) NOT NULL,
    kernel         varchar(128) NOT NULL,
    arch           varchar(32)  NOT NULL,
    agent_version  varchar(32)  NOT NULL,
    enrolled_at    timestamptz  NOT NULL,
    -- Last successful enrollment or scan submission; drives ONLINE/STALE.
    last_seen_at   timestamptz  NOT NULL,
    -- Denormalised pointer to the host's newest scan by (finished_at, id), maintained by ingest
    -- under the host row lock. Every "latest scan per host" read model joins through it instead of
    -- running a DISTINCT ON / window query over the whole scans table.
    latest_scan_id uuid,
    CONSTRAINT hosts_pkey PRIMARY KEY (id),
    CONSTRAINT hosts_machine_id_key UNIQUE (machine_id),
    -- Also the index that authenticates every scan submission.
    CONSTRAINT hosts_token_hash_key UNIQUE (token_hash),
    CONSTRAINT hosts_token_hash_format CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

-- The catalog is upserted from scan reports; it reflects the most recently ingested definition of
-- each check. Scan results reference it for title, category and severity.
CREATE TABLE checks (
    id            varchar(64)  NOT NULL,
    title         varchar(200) NOT NULL,
    category      text         NOT NULL,
    severity      text         NOT NULL,
    first_seen_at timestamptz  NOT NULL,
    updated_at    timestamptz  NOT NULL,
    CONSTRAINT checks_pkey PRIMARY KEY (id),
    CONSTRAINT checks_id_format CHECK (id ~ '^[a-z0-9_.]{3,64}$'),
    CONSTRAINT checks_category_valid CHECK (category IN ('ssh', 'accounts', 'network', 'kernel', 'filesystem')),
    CONSTRAINT checks_severity_valid CHECK (severity IN ('low', 'medium', 'high', 'critical'))
);

CREATE TABLE scans (
    -- Generated by the agent before submission; the primary key is what makes ingest idempotent.
    id                   uuid        NOT NULL,
    host_id              uuid        NOT NULL,
    agent_version        varchar(32) NOT NULL,
    started_at           timestamptz NOT NULL,
    finished_at          timestamptz NOT NULL,
    received_at          timestamptz NOT NULL,
    -- Computed once at ingest from the severities in the report, so a later change to a check's
    -- severity in the catalog never rewrites history. NULL when no check was applicable.
    score                numeric(4, 1),
    pass_count           integer     NOT NULL,
    fail_count           integer     NOT NULL,
    error_count          integer     NOT NULL,
    not_applicable_count integer     NOT NULL,
    CONSTRAINT scans_pkey PRIMARY KEY (id),
    CONSTRAINT scans_host_fkey FOREIGN KEY (host_id) REFERENCES hosts (id),
    CONSTRAINT scans_started_before_finished CHECK (started_at <= finished_at),
    CONSTRAINT scans_score_range CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT scans_counts_non_negative
        CHECK (pass_count >= 0 AND fail_count >= 0 AND error_count >= 0 AND not_applicable_count >= 0)
);

-- Serves a host's scan history (newest first), the previous/next scan lookups that drift detection
-- runs on ingest, and the per-bucket carry-forward lookups of the fleet trend. (finished_at, id) is
-- the total order used for "previous scan" everywhere, so ties on finished_at are deterministic.
CREATE INDEX scans_host_finished_idx ON scans (host_id, finished_at DESC, id DESC);

ALTER TABLE hosts
    ADD CONSTRAINT hosts_latest_scan_fkey FOREIGN KEY (latest_scan_id) REFERENCES scans (id);

CREATE TABLE scan_results (
    scan_id  uuid          NOT NULL,
    check_id varchar(64)   NOT NULL,
    status   text          NOT NULL,
    expected varchar(200),
    actual   varchar(200),
    evidence varchar(1000),
    -- Also serves every lookup by scan and the (latest scan, check) probes of the check read models.
    CONSTRAINT scan_results_pkey PRIMARY KEY (scan_id, check_id),
    CONSTRAINT scan_results_scan_fkey FOREIGN KEY (scan_id) REFERENCES scans (id),
    -- No index on check_id: checks are never deleted, and no query scans results by check alone.
    CONSTRAINT scan_results_check_fkey FOREIGN KEY (check_id) REFERENCES checks (id),
    CONSTRAINT scan_results_status_valid CHECK (status IN ('PASS', 'FAIL', 'ERROR', 'NOT_APPLICABLE'))
);

-- One row per check whose status differs between a scan and the host's previous scan. Statuses and
-- evidence are copied so an event reads as a self-contained record of what was observed.
CREATE TABLE drift_events (
    id               uuid          NOT NULL DEFAULT uuidv7(),
    host_id          uuid          NOT NULL,
    scan_id          uuid          NOT NULL,
    previous_scan_id uuid          NOT NULL,
    check_id         varchar(64)   NOT NULL,
    from_status      text          NOT NULL,
    to_status        text          NOT NULL,
    from_evidence    varchar(1000),
    to_evidence      varchar(1000),
    direction        text          NOT NULL,
    -- finished_at of scan_id, copied so the event feed sorts without joining scans.
    detected_at      timestamptz   NOT NULL,
    CONSTRAINT drift_events_pkey PRIMARY KEY (id),
    CONSTRAINT drift_events_host_fkey FOREIGN KEY (host_id) REFERENCES hosts (id),
    CONSTRAINT drift_events_scan_fkey FOREIGN KEY (scan_id) REFERENCES scans (id),
    CONSTRAINT drift_events_previous_scan_fkey FOREIGN KEY (previous_scan_id) REFERENCES scans (id),
    CONSTRAINT drift_events_check_fkey FOREIGN KEY (check_id) REFERENCES checks (id),
    -- At most one event per check per scan; also the index used to replace a scan's events when an
    -- out-of-order scan is inserted before it.
    CONSTRAINT drift_events_scan_check_key UNIQUE (scan_id, check_id),
    CONSTRAINT drift_events_status_changed CHECK (from_status <> to_status),
    CONSTRAINT drift_events_from_status_valid CHECK (from_status IN ('PASS', 'FAIL', 'ERROR', 'NOT_APPLICABLE')),
    CONSTRAINT drift_events_to_status_valid CHECK (to_status IN ('PASS', 'FAIL', 'ERROR', 'NOT_APPLICABLE')),
    CONSTRAINT drift_events_direction_valid CHECK (direction IN ('REGRESSED', 'RESOLVED', 'CHANGED'))
);

-- The fleet-wide event feed (newest first, optionally filtered by direction).
CREATE INDEX drift_events_detected_idx ON drift_events (detected_at DESC, id DESC);
-- The same feed filtered to one host.
CREATE INDEX drift_events_host_detected_idx ON drift_events (host_id, detected_at DESC, id DESC);
